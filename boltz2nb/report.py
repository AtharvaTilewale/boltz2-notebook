def _img(path: str | None) -> str:
    if not path or not Path(path).exists():
        return ""
    b64 = base64.b64encode(Path(path).read_bytes()).decode()
    return f'<img src="data:image/png;base64,{b64}" alt="{html.escape(Path(path).name)}">'


def _fmt(v: Any) -> str:
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.3f}"
    return html.escape(str(v))


def _table(rows, columns) -> str:
    head = "".join(f"<th>{html.escape(c)}</th>" for c in columns)
    body = "".join("<tr>" + "".join(f"<td>{_fmt(r.get(c))}</td>" for c in columns) + "</tr>" for r in rows)
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def build_report(job: JobResult, plots: dict[str, Any], run_context: dict[str, Any] | None = None,
                 ligand_svg: str | None = None, embed_structure: bool = True) -> str:
    s = summary_dict(job)
    best = job.best
    parts = [f"<!doctype html><html><head><meta charset='utf-8'><title>Boltz2 report - {html.escape(job.job_name)}</title>",
             f"<style>{_CSS}</style></head><body>",
             f"<h1>Boltz2 report: <code>{html.escape(job.job_name)}</code></h1>",
             f"<p>Generated by boltz2nb {__version__}. {s['n_models']} diffusion sample(s); model {s['best_model']} is Boltz's top-ranked sample.</p>"]

    # Chains
    for note in s.get("layout_notes", []):
        parts.append(f"<p class='note'><strong>Per-token analysis unavailable:</strong> {html.escape(note)}</p>")
    if s["chains"]:
        parts.append("<h2>Chain confidence (best model)</h2>")
        parts.append(_table(s["chains"], ["chain_id", "kind", "n_tokens", "mean_plddt", "min_plddt", "pct_confident", "pct_very_high", "assessment"]))
    if s["interface_pae"]:
        parts.append("<p><strong>Inter-chain PAE (Å, lower is better):</strong> " +
                     ", ".join(f"{k}: {v:.1f}" for k, v in s["interface_pae"].items()) + "</p>")

    # Ensemble
    parts.append("<h2>Per-sample metrics</h2>")
    cols = ["model", "confidence_score", "ptm", "iptm", "ligand_iptm", "protein_iptm", "complex_plddt", "complex_iplddt", "complex_pde", "mean_plddt"]
    cols += [c for c in s["models"][0] if c.startswith("pae_")]
    parts.append(_table(s["models"], cols))
    ens = s["ensemble"]
    if ens["n_models"] > 1:
        rows = [{"metric": k, **v} for k, v in ens.items() if isinstance(v, dict) and "mean" in v and k != "interface_pae"]
        parts.append("<p><strong>Ensemble (mean ± SD across samples):</strong></p>")
        parts.append(_table(rows, ["metric", "mean", "sd", "min", "max"]))
        if plots.get("ensemble"):
            parts.append(_img(plots["ensemble"]))
    else:
        parts.append("<p class='note'>Only one diffusion sample was generated. Set <code>diffusion_samples ≥ 3</code> to obtain a spread estimate for the confidence and affinity metrics.</p>")

    # Affinity
    if s["affinity"]:
        a = s["affinity"]
        parts.append("<h2>Binding affinity (Boltz-2 affinity module)</h2>")
        parts.append(f"<p>Binding probability <strong>{a['binding_probability']:.2f}</strong> ({a['probability_class']}). "
                     f"Predicted log<sub>10</sub> IC<sub>50</sub> (µM) = <strong>{a['log10_ic50_um']:.2f}</strong> → IC<sub>50</sub> ≈ <strong>{a['ic50']}</strong>, "
                     f"pIC<sub>50</sub> ≈ {a['pic50']:.2f}, ΔG ≈ {a['delta_g_kcal_mol_approx']:.1f} kcal/mol (approximate; IC<sub>50</sub> treated as K<sub>d</sub>). {a['potency_class']}.</p>")
        if a["ensemble_members"]:
            parts.append(_table(a["ensemble_members"], ["model", "value", "probability"]))
            if a["member_spread"] > 1.0:
                parts.append(f"<p class='note'>The two affinity ensemble members disagree by {a['member_spread']:.2f} log units (≥10x in IC50); treat the value as uncertain.</p>")
        parts.append("<p class='note'>Use the binding probability for hit discovery (binder vs decoy) and the IC<sub>50</sub> value only to rank close analogues. "
                     "The affinity module is trained on small molecules; it is not meaningful for peptides or protein binders.</p>")
        parts.append(_img(plots.get("affinity")))
        if ligand_svg:
            parts.append(f"<div>{ligand_svg}</div>")

    # Plots
    if any(p.get("plddt") or p.get("pae") for p in plots.get("models", {}).values()):
        parts.append("<h2>Confidence plots</h2>")
        for mid, p in plots.get("models", {}).items():
            parts.append(f"<h3>Model {mid}</h3><div class='grid'>{_img(p.get('plddt'))}{_img(p.get('pae'))}</div>")
        parts.append("<p class='note'>PAE is asymmetric: rows are the aligned token, columns the scored token. "
                     "The colour scale is fixed at 0-32 Å so plots are comparable between jobs. "
                     f"Token convention: {html.escape(str(s.get('token_layout', 'atomised')))}.</p>")

    # Structure
    if embed_structure and best.structure_path.suffix.lower() == ".pdb":
        pdb = json.dumps(best.structure_path.read_text())
        parts.append("<h2>Structure (best model, coloured by pLDDT)</h2><div id='viewer'></div>")
        parts.append("<script src='https://3Dmol.org/build/3Dmol-min.js'></script><script>"
                     f"const pdb={pdb};const v=$3Dmol.createViewer(document.getElementById('viewer'),{{backgroundColor:'white'}});"
                     "v.addModel(pdb,'pdb');v.setStyle({},{cartoon:{colorscheme:{prop:'b',gradient:'roygb',min:50,max:90}}});"
                     "v.addStyle({hetflag:true},{stick:{}});v.zoomTo();v.render();</script>")

    # Provenance
    if run_context:
        parts.append("<h2>Provenance</h2><table><tbody>")
        for k in ("engine", "boltz2nb_version", "python", "gpu_name", "timestamp_utc", "input_yaml_sha1"):
            if run_context.get(k) is not None:
                parts.append(f"<tr><td>{k}</td><td style='text-align:left'>{html.escape(str(run_context[k]))}</td></tr>")
        parts.append("</tbody></table>")
        if run_context.get("command"):
            parts.append(f"<p><code>{html.escape(' '.join(map(str, run_context['command'])))}</code></p>")
        if run_context.get("input_yaml"):
            parts.append(f"<details><summary>Input YAML</summary><pre>{html.escape(run_context['input_yaml'])}</pre></details>")
    parts.append("</body></html>")
    return "".join(parts)


def write_report(job: JobResult, out_dir: Path | str, run_context: dict[str, Any] | None = None,
                 ligand_svg: str | None = None) -> dict[str, Any]:
    out_dir = Path(out_dir)
    plots = generate_plots(job, out_dir / "plots")
    summary = summary_dict(job)
    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2, default=str))
    report_path = out_dir / f"{job.job_name}_report.html"
    report_path.write_text(build_report(job, plots, run_context, ligand_svg))
    return {"report": str(report_path), "summary": str(out_dir / "summary.json"), "plots": plots}
